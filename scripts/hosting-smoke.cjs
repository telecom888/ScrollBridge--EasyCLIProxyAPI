const { _electron: electron }=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path'),fs=require('node:fs');
(async()=>{
 const dir=path.resolve('.test-output/hosting-smoke-'+Date.now());fs.mkdirSync(dir,{recursive:true});
 const env={...process.env,SCROLLBRIDGE_TEST_DATA:dir};delete env.ELECTRON_RUN_AS_NODE;
 const app=await electron.launch({executablePath:require('electron'),args:['.'],env});
 try{
  const win=await app.firstWindow();
  await win.waitForFunction(()=>typeof snapshot!=='undefined'&&!!snapshot);
  await win.click('[data-page=hosting]');
  assert.equal(await win.locator('#hosting-title').innerText(),'添加密钥');
  await win.fill('#hosting-name','第一密钥');
  await win.fill('#hosting-key','synthetic-openai-key-for-test');
  await win.click('#hosting-form button[type=submit]');
  await win.waitForFunction(()=>snapshot.config.hostingProviders.length===1&&!pending);
  await win.fill('#hosting-manual-id','shared-test');
  await win.click('#hosting-manual-add');
  await win.waitForFunction(()=>snapshot.config.hostingModels.length===1&&!pending);
  await win.click('#hosting-add');
  await win.fill('#hosting-name','第二密钥');
  await win.fill('#hosting-key','synthetic-second-key-for-test');
  await win.click('#hosting-form button[type=submit]');
  await win.waitForFunction(()=>snapshot.config.hostingProviders.length===2&&!pending);
  await win.fill('#hosting-manual-id','shared-test');
  await win.click('#hosting-manual-add');
  await win.waitForFunction(()=>snapshot.config.hostingModels.length===2&&!pending);
  assert.equal(await win.locator('.hosting-route-group').count(),1);
  await win.click('[data-page=settings]');
  await win.locator('#showModelSources').check();
  await win.waitForFunction(()=>snapshot.config.showModelSources&&!pending);
  await win.locator('#unifiedModelRouting').check();
  await win.waitForFunction(()=>snapshot.config.unifiedModelRouting&&!pending);
  await win.click('[data-page=catalog]');
  const sourceText=await win.locator('#hosted-catalog-list').innerText();
  assert.match(sourceText,/第一密钥/);assert.match(sourceText,/第二密钥/);
  const ids=await win.evaluate(()=>snapshot.modelEntries.filter(m=>m.hosted).map(m=>m.name));
  assert.deepEqual(ids,['shared-test','shared-test']);
  await win.click('[data-page=hosting]');
  await win.locator('.hosting-route-row').nth(1).getByRole('button',{name:/上移/}).click();
  await win.waitForFunction(()=>Object.values(snapshot.config.hostingRouteOrders).some(arr=>arr.length===2)&&!pending);
  const state=await win.evaluate(()=>snapshot.config);
  assert.equal(state.hostingRouteOrders['shared-test'][0],state.hostingModels[1].id);
  assert.equal(JSON.stringify(await win.evaluate(()=>window.bridge.invoke('snapshot'))).includes('synthetic-openai-key-for-test'),false);
  await win.click('#hosting-delete');
  await win.locator('#confirm-action-accept').click();
  await win.waitForFunction(()=>snapshot.config.hostingProviders.length===1&&!pending);
  const after=await win.evaluate(()=>snapshot.config);
  assert.equal(after.hostingModels.length,1);
  console.log('Hosting CRUD, duplicate route priority, source display and snapshot redaction verified');
 }finally{await app.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
